/**
 * 게임 연출 글자(`.game-cue`)의 최대 크기(px).
 *
 * 카운트다운(3-2-1-START)과 종료 화면(GAME OVER / CLEAR!)이 공유한다. 실제 크기는
 * `useFitText`가 창 폭에 맞춰 이 값 **이하로** 정하므로, 짧은 라벨은 여기 걸려
 * 멈추고 긴 라벨만 줄어든다.
 *
 * 값의 근거는 예전 CSS의 `clamp(2.5rem, 19cqw, 5rem)` 상한(5rem = 80px)이다.
 * 그 clamp에서 실제로 쓰이던 구간은 19cqw였고 상한 80px에는 닿지 않았지만,
 * 상한을 그대로 물려받으면 짧은 라벨이 예전보다 커진다 — 카운트다운 연출은
 * 2026-08-11에 이란토가 튜닝한 것이라 크기를 유지해야 한다. 그래서 당시 실제
 * 크기(390px 화면에서 약 60px)에 맞춰 60으로 잡았다.
 *
 * **줄이려면 카운트다운도 같이 작아진다는 것을 알고 바꿀 것.** 종료 화면의 넘침은
 * 이 값이 아니라 `useFitText`가 막는다 — 넘친다고 이 값을 낮추는 것은 잘못된 처방이다.
 */
export const GAME_CUE_MAX_PX = 60;
