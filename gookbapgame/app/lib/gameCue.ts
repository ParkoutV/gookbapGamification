/**
 * 게임 연출 글자(`.game-cue`)의 최대 크기(px).
 *
 * 카운트다운(3-2-1-START)과 종료 화면(GAME OVER / CLEAR!)이 공유한다. 실제 크기는
 * `useFitText`가 창 폭에 맞춰 이 값 **이하로** 정하므로, 짧은 라벨은 여기 걸려
 * 멈추고 긴 라벨만 줄어든다.
 *
 * **처음에 60으로 잡았다가 84로 올렸다**(2026-08-12, 이란토 "너무 작지 않니?").
 * 60은 예전 `19cqw`가 390px 화면에서 실제로 만들던 크기였는데, 그것을 그대로
 * 상한으로 옮긴 것이 잘못이었다. `cqw`는 창이 넓어지면 글자도 같이 커지지만
 * 고정 상한은 그렇지 않아서, **어느 화면에서도 60px에 묶여 버렸다.**
 * 그 결과 CLEAR!가 창 폭의 68%밖에 차지하지 못해 연출 문구인데도 아래 버튼보다
 * 존재감이 약했다.
 *
 * 84px이면 CLEAR!가 창 안쪽(340px)의 약 89%를 채운다. 패널이 `max-w-sm`(384px)로
 * 묶여 있어 **큰 화면에서도 창 안쪽은 340px이 최대**이므로, 이 값 하나로 모든
 * 화면이 같은 비율을 갖는다 — 데스크톱만의 문제가 아니었다.
 *
 * **줄이면 카운트다운(3-2-1-START)도 같이 작아진다는 것을 알고 바꿀 것.**
 * 종료 화면의 넘침은 이 값이 아니라 `useFitText`가 막는다(GAME OVER는 길어서
 * 여기 닿지 않고 자동으로 줄어든다) — 넘친다고 이 값을 낮추는 것은 잘못된 처방이다.
 */
export const GAME_CUE_MAX_PX = 84;
