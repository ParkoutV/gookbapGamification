import { test } from "node:test";
import assert from "node:assert/strict";
import { rankingPeriodStart } from "./rankingPeriod.ts";

/**
 * 경계는 **실제 시점**이어야 한다. KST 오늘 00:00 = UTC 어제 15:00이므로 기대값을 그
 * 형태로 적는다 — `T00:00:00Z`가 기대값에 나타나면 그것이 9시간 구멍이다.
 */
const iso = (period: Parameters<typeof rankingPeriodStart>[0], now: string) =>
  rankingPeriodStart(period, new Date(now))?.toISOString() ?? null;

test("total은 경계가 없다", () => {
  assert.equal(rankingPeriodStart("total", new Date("2026-08-13T04:00:00Z")), null);
});

/*
 * **이 저장소가 정확히 여기서 조용히 틀릴 수 있다.** `kstDayStart`(couponRemaining.ts)를
 * 재사용해 `T00:00:00Z`로 경계를 만들면 KST 00:00~09:00에 플레이한 기록이 통째로
 * 사라지고 오류는 나지 않는다. 아래 세 시각은 모두 KST 8/13이므로 daily 경계가 항상
 * UTC 8/12 15:00이어야 한다.
 */
test("daily: KST 00:00~09:00 구간에서도 경계가 KST 오늘 00:00이다", () => {
  // KST 8/13 00:30 (UTC 8/12 15:30) — 구멍의 시작
  assert.equal(iso("daily", "2026-08-12T15:30:00Z"), "2026-08-12T15:00:00.000Z");
  // KST 8/13 08:59 (UTC 8/12 23:59) — 구멍의 끝
  assert.equal(iso("daily", "2026-08-12T23:59:00Z"), "2026-08-12T15:00:00.000Z");
  // KST 8/13 13:00 (UTC 8/13 04:00) — 구멍 밖. 같은 값이어야 한다.
  assert.equal(iso("daily", "2026-08-13T04:00:00Z"), "2026-08-12T15:00:00.000Z");
});

test("daily: KST 자정을 넘기면 경계도 하루 넘어간다", () => {
  // KST 8/13 23:30 (UTC 8/13 14:30)
  assert.equal(iso("daily", "2026-08-13T14:30:00Z"), "2026-08-12T15:00:00.000Z");
  // KST 8/14 00:30 (UTC 8/13 15:30) — 60분 차이지만 날짜가 넘어갔다.
  assert.equal(iso("daily", "2026-08-13T15:30:00Z"), "2026-08-13T15:00:00.000Z");
});

/*
 * weekly·monthly는 **롤링 윈도우**다(2026-08-14). 달력 기준이면 월요일 오전과 매월
 * 1일에 탭이 통째로 비는데, 매장 QR로 막 들어온 사람이 그 빈 화면을 본다.
 *
 * **오늘을 포함해 센다** — "최근 7일"은 오늘 + 지난 6일이라 경계는 6일 전 00:00이다.
 * 7을 그대로 빼면 8일치가 잡힌다.
 */
test("weekly: 경계는 6일 전 KST 00:00이다 — 오늘을 포함해 7일", () => {
  // KST 8/13 13:00 → 8/7 00:00 (8/7~8/13이 7일)
  assert.equal(iso("weekly", "2026-08-13T04:00:00Z"), "2026-08-06T15:00:00.000Z");
});

test("weekly: 요일과 무관하다 — 월요일에도 창이 리셋되지 않는다", () => {
  // 2026-08-10이 월요일. 달력 기준이면 여기서 그날 00:00으로 튀어 랭킹이 비었다.
  assert.equal(iso("weekly", "2026-08-10T01:00:00Z"), "2026-08-03T15:00:00.000Z");
  // 하루 전(일요일)과 정확히 하루 차이여야 한다 — 창이 하루씩 미끄러진다.
  assert.equal(iso("weekly", "2026-08-09T01:00:00Z"), "2026-08-02T15:00:00.000Z");
});

test("monthly: 경계는 29일 전 KST 00:00이다 — 오늘을 포함해 30일", () => {
  // KST 8/13 13:00 → 7/15 00:00
  assert.equal(iso("monthly", "2026-08-13T04:00:00Z"), "2026-07-14T15:00:00.000Z");
});

test("monthly: 1일에도 창이 리셋되지 않는다", () => {
  // KST 8/1 00:30. 달력 기준이면 그날 00:00이라 랭킹이 통째로 비었다.
  assert.equal(iso("monthly", "2026-07-31T15:30:00Z"), "2026-07-02T15:00:00.000Z");
});

test("KST 00:00~09:00 구간에서도 창이 어긋나지 않는다", () => {
  // KST 8/13 00:30과 13:00은 같은 날이므로 경계가 같아야 한다.
  assert.equal(iso("weekly", "2026-08-12T15:30:00Z"), "2026-08-06T15:00:00.000Z");
  assert.equal(iso("monthly", "2026-08-12T15:30:00Z"), "2026-07-14T15:00:00.000Z");
});

/* 연·월 경계를 거슬러 올라가도 날짜 칸 계산이라 틀릴 자리가 없다. */
test("연말·윤년을 거슬러 올라가도 맞는다", () => {
  // KST 2027-01-01 00:30 → weekly는 2026-12-26, monthly는 2026-12-03
  assert.equal(iso("weekly", "2026-12-31T15:30:00Z"), "2026-12-25T15:00:00.000Z");
  assert.equal(iso("monthly", "2026-12-31T15:30:00Z"), "2026-12-02T15:00:00.000Z");
  // 2028은 윤년 — 2/29에서 30일 전은 1/31이다.
  assert.equal(iso("monthly", "2028-02-29T01:00:00Z"), "2028-01-30T15:00:00.000Z");
});
