/**
 * 랭킹 목록 영역의 고정 높이(px).
 *
 * **네 상태(로딩·실패·빈 목록·목록)가 이 값을 공유해야 한다.** 예전에는 목록에만
 * `h-[236px]`이 리터럴로 박혀 있고 나머지 세 상태는 한 줄짜리 문단이라, 탭을 옮길
 * 때마다 그 차이만큼 창이 줄었다 늘었다 했다(2026-08-14 이란토 실기 제보).
 * `loaded.period !== period`가 곧 "아직 안 온 것"이라 **탭 전환은 반드시 로딩 구간을
 * 지난다** — 즉 출렁임은 예외가 아니라 매번 일어나는 일이었다.
 *
 * 목록 높이의 근거: 한 줄 20px + gap 4px × 9 = 236px. 마지막 페이지가 10건 미만일 때
 * 패널이 줄어들어 페이지 버튼과 '닫기'가 위로 튀는 것을 막으려고 2026-08-13에 넣었다.
 * **이 근거를 지우지 말 것.**
 *
 * `HEADER_H`는 헤더 행(등수/닉네임/점수)의 몫이다. 그 행도 **목록이 있을 때만**
 * 렌더되므로, 목록 높이만 맞추고 헤더를 빼면 딱 그만큼 잔여 출렁임이 남는다.
 *
 * 값은 브라우저 실측이다(320px, 2026-08-15): 박스 20.6px + `mb-1` 4px = 24.6px.
 * **계산으로 잡지 말 것** — `text-xs`의 line-height는 16px이지만 실제 박스는 20.6px이고
 * (`pb-1` 4px + 테두리), 테두리는 기기 픽셀 비율에 따라 0.606px처럼 소수로 렌더된다.
 * 25px로 어림하면 그 차이만큼 목록 상태에서만 패널이 높아진다.
 *
 * **Tailwind 임의값 클래스(`h-[236px]`)로 되돌리지 말 것.** Tailwind v4는 소스 텍스트를
 * 훑어 클래스를 생성하므로 JS 변수로 클래스명을 조립하면 그 클래스가 아예 만들어지지
 * 않고 높이가 조용히 0이 된다. 인라인 `style`로 넘겨야 한 값을 네 곳이 나눠 쓸 수 있다.
 */
export const RANKING_LIST_H = 236;

/** 헤더 행 높이(실측 24.6px). 목록과 함께만 렌더되므로 고정 블록에 포함해야 한다. */
export const RANKING_HEADER_H = 24.6;

/**
 * 목록 영역 전체 높이 — 로딩·실패·빈 목록 세 상태가 이 값으로 자리를 채운다.
 * 목록 상태는 헤더와 `<ol>`이 각각 자기 몫을 차지하므로 합이 같아진다.
 */
export const RANKING_BODY_H = RANKING_LIST_H + RANKING_HEADER_H;
